const plural = (n, one, many) => (Number(n) === 1 ? one : many);
/** 1st, 2nd, 3rd, 4th, … 11th, 12th, 13th, 21st */
function ordinal(n) {
  const k = Number(n);
  const suffix = k % 100 >= 11 && k % 100 <= 13 ? 'th' : ['th', 'st', 'nd', 'rd'][k % 10] ?? 'th';
  return `${k}${suffix}`;
}

