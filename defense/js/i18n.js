/** 받침에 맞는 목적격 조사: 궁수탑을, 대포를 */
function withObject(word) {
  const code = word.charCodeAt(word.length - 1) - 0xac00;
  return word + (code >= 0 && code <= 11171 && code % 28 > 0 ? '을' : '를');
}

