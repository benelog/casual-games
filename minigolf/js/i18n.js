const ordinal = (n) => {
  const k = Number(n);
  const suffix = k % 100 >= 11 && k % 100 <= 13 ? 'th' : ['th', 'st', 'nd', 'rd'][k % 10] ?? 'th';
  return `${k}${suffix}`;
};
const shotNthEn = ({ n }) => `${ordinal(n)} shot`;
const penaltyShortEn = ({ n }) => `${n} penalty ${Number(n) === 1 ? 'stroke' : 'strokes'}`;
const pickedUpEn = ({ max }) => `Picked up at the ${max}-stroke limit`;

